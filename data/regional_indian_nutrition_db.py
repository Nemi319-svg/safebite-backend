class RegionalNutritionDatabase:
    """Singleton query interface for regional food nutritional analysis."""

    def __init__(self):
        self._foods: Dict[str, RegionalFoodItem] = {}
        self._load_dataset()

    def _load_dataset(self):
        for raw in REGIONAL_FOODS_DATA:
            item = RegionalFoodItem(
                food_id=raw["food_id"],
                name=raw["name"],
                regional_name=raw["regional_name"],
                region=raw["region"],
                state=raw["state"],
                category=raw["category"],
                serving_size_g=raw["serving_size_g"],
                calories=raw["calories"],
                protein_g=raw["protein_g"],
                carbs_g=raw["carbs_g"],
                dietary_fiber_g=raw["dietary_fiber_g"],
                net_carbs_g=raw["net_carbs_g"],
                sugar_g=raw["sugar_g"],
                added_sugar_g=raw["added_sugar_g"],
                fat_g=raw["fat_g"],
                saturated_fat_g=raw["saturated_fat_g"],
                polyunsaturated_fat_g=raw["polyunsaturated_fat_g"],
                monounsaturated_fat_g=raw["monounsaturated_fat_g"],
                trans_fat_g=raw["trans_fat_g"],
                sodium_mg=raw["sodium_mg"],
                potassium_mg=raw["potassium_mg"],
                calcium_mg=raw["calcium_mg"],
                iron_mg=raw["iron_mg"],
                vitamin_c_mg=raw["vitamin_c_mg"],
                glycemic_index=raw["glycemic_index"],
                glycemic_load=raw["glycemic_load"],
                is_diabetic_safe=raw["is_diabetic_safe"],
                diabetic_caution_reason=raw.get("diabetic_caution_reason"),
                is_hypertension_safe=raw["is_hypertension_safe"],
                is_heart_healthy=raw["is_heart_healthy"],
                is_gluten_free=raw["is_gluten_free"],
                is_vegan=raw["is_vegan"],
                is_vegetarian=raw["is_vegetarian"],
                ayurvedic_dosha=raw["ayurvedic_dosha"],
                seasonal_suitability=raw["seasonal_suitability"],
                health_score=raw["health_score"],
                primary_ingredients=raw["primary_ingredients"],
                healthier_substitutes=raw["healthier_substitutes"],
                health_benefits=raw["health_benefits"],
                health_concerns=raw["health_concerns"],
            )
            self._foods[item.food_id] = item

    def get_by_id(self, food_id: str) -> Optional[RegionalFoodItem]:
        return self._foods.get(food_id)

    def search_by_name(self, query: str) -> List[RegionalFoodItem]:
        q = query.strip().lower()
        results = []
        for item in self._foods.values():
            if q in item.name.lower() or q in item.regional_name.lower() or any(q in ing.lower() for ing in item.primary_ingredients):
                results.append(item)
        return results

    def filter_foods(
        self,
        region: Optional[str] = None,
        state: Optional[str] = None,
        is_diabetic_safe: Optional[bool] = None,
        is_gluten_free: Optional[bool] = None,
        is_vegan: Optional[bool] = None,
        min_health_score: Optional[int] = None,
        max_glycemic_load: Optional[float] = None
    ) -> List[RegionalFoodItem]:
        results = []
        for f in self._foods.values():
            if region and f.region.lower() != region.lower():
                continue
            if state and f.state.lower() != state.lower():
                continue
            if is_diabetic_safe is not None and f.is_diabetic_safe != is_diabetic_safe:
                continue
            if is_gluten_free is not None and f.is_gluten_free != is_gluten_free:
                continue
            if is_vegan is not None and f.is_vegan != is_vegan:
                continue
            if min_health_score is not None and f.health_score < min_health_score:
                continue
            if max_glycemic_load is not None and f.glycemic_load > max_glycemic_load:
                continue
            results.append(f)
        return results

    def get_all(self) -> List[RegionalFoodItem]:
        return list(self._foods.values())


# Global singleton instance
regional_food_db = RegionalNutritionDatabase()
