def lookup_packaged_barcode(barcode: str) -> Optional[Dict[str, Any]]:
    """
    Looks up a packaged product by barcode.
    Handles leading and missing zero variations in EAN-13 barcodes.
    """
    clean = barcode.strip()
    return (
        PACKAGED_FOOD_BARCODE_CATALOG.get(clean) or
        PACKAGED_FOOD_BARCODE_CATALOG.get(clean.lstrip("0")) or
        PACKAGED_FOOD_BARCODE_CATALOG.get("0" + clean)
    )


def search_packaged_products_by_keyword(query: str) -> List[Dict[str, Any]]:
    """
    Searches the catalog by product name, brand, or category.
    """
    q = query.lower().strip()
    results = []
    for item in PACKAGED_FOOD_BARCODE_CATALOG.values():
        if (q in item["name"].lower() or
            q in item["brand"].lower() or
            q in item["category"].lower()):
            results.append(item)
    return results


def filter_by_traffic_light(color: str) -> List[Dict[str, Any]]:
    """
    Returns products classified under GREEN, YELLOW, or RED traffic light indicator.
    """
    target = color.upper().strip()
    return [p for p in PACKAGED_FOOD_BARCODE_CATALOG.values() if p["traffic_light"] == target]
