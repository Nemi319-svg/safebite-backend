def get_food_clinical_profile(food_key: str) -> Optional[Dict[str, Any]]:
    """Retrieve detailed clinical profile for a specific food key."""
    return CLINICAL_FOOD_DATABASE.get(food_key.lower().strip())


def search_clinical_foods(
    category: Optional[str] = None,
    gluten_free_only: bool = False,
    max_potassium_mg: Optional[float] = None,
    max_purine_mg: Optional[float] = None,
    max_oxalate_mg: Optional[float] = None,
    max_glycemic_index: Optional[int] = None
) -> List[Dict[str, Any]]:
    """
    Search and filter clinical food database based on medical constraints.
    """
    results = []
    for key, food in CLINICAL_FOOD_DATABASE.items():
        if category and food.get("category") != category:
            continue
        if gluten_free_only and not food.get("gluten_free", False):
            continue
        if max_potassium_mg is not None and food.get("potassium_mg", 0) > max_potassium_mg:
            continue
        if max_purine_mg is not None and food.get("purine_mg", 0) > max_purine_mg:
            continue
        if max_oxalate_mg is not None and food.get("oxalate_mg", 0) > max_oxalate_mg:
            continue
        if max_glycemic_index is not None and food.get("glycemic_index", 100) > max_glycemic_index:
            continue
        
        item = dict(food)
        item["food_key"] = key
        results.append(item)
    return results
